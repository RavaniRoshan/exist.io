// ErrNotFound is returned when a query matches no row.
var ErrNotFound = errors.New("store: not found")

// ErrConflict is returned when a uniqueness constraint is violated.
var ErrConflict = errors.New("store: conflict")

func now() string { return time.Now().UTC().Format(time.RFC3339Nano) }

// ---------- Namespaces ----------

// Namespace is a team or user namespace (the {owner} in Origin URLs).
type Namespace struct {
	ID          string
	Slug        string
	Type        string // user | team
	Name        string
	OwnerUserID string
	CreatedAt   string
	UpdatedAt   string
}

// CreateNamespace inserts a namespace. id is generated by the caller (idgen).
func (db *DB) CreateNamespace(ctx context.Context, ns Namespace) error {
	_, err := db.sql.ExecContext(ctx, `INSERT INTO namespaces
		(id, slug, type, name, owner_user_id, created_at, updated_at)
		VALUES (?,?,?,?,?,?,?)`,
		ns.ID, ns.Slug, ns.Type, ns.Name, nullStr(ns.OwnerUserID), now(), now())
	if err != nil {
		if isConflict(err) {
			return fmt.Errorf("%w: namespace slug %q", ErrConflict, ns.Slug)
		}
		return err
	}
	return nil
}

// GetNamespaceBySlug returns the namespace with the given slug.
func (db *DB) GetNamespaceBySlug(ctx context.Context, slug string) (Namespace, error) {
	row := db.sql.QueryRowContext(ctx, `SELECT id, slug, type, name, owner_user_id, created_at, updated_at
		FROM namespaces WHERE slug = ?`, slug)
	return scanNamespace(row)
}

// GetNamespace returns the namespace by id.
func (db *DB) GetNamespace(ctx context.Context, id string) (Namespace, error) {
	row := db.sql.QueryRowContext(ctx, `SELECT id, slug, type, name, owner_user_id, created_at, updated_at
		FROM namespaces WHERE id = ?`, id)
	return scanNamespace(row)
}

// ListNamespaces returns namespaces ordered by slug, up to limit.
func (db *DB) ListNamespaces(ctx context.Context, limit int) ([]Namespace, error) {
	if limit <= 0 {
		limit = 30
	}
	if limit > 100 {
		limit = 100
	}
	rows, err := db.sql.QueryContext(ctx, `SELECT id, slug, type, name, owner_user_id, created_at, updated_at
		FROM namespaces ORDER BY slug ASC LIMIT ?`, limit)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []Namespace
	for rows.Next() {
		var ns Namespace
		var owner sql.NullString
		if err := rows.Scan(&ns.ID, &ns.Slug, &ns.Type, &ns.Name, &owner, &ns.CreatedAt, &ns.UpdatedAt); err != nil {
			return nil, err
		}
		ns.OwnerUserID = owner.String
		out = append(out, ns)
	}
	return out, rows.Err()
}

func scanNamespace(row *sql.Row) (Namespace, error) {
	var ns Namespace
	var owner sql.NullString
	err := row.Scan(&ns.ID, &ns.Slug, &ns.Type, &ns.Name, &owner, &ns.CreatedAt, &ns.UpdatedAt)
	if errors.Is(err, sql.ErrNoRows) {
		return Namespace{}, ErrNotFound
	}
	if err != nil {
		return Namespace{}, err
	}
	ns.OwnerUserID = owner.String
	return ns, nil
}

// ---------- Repos ----------

// Repo is a stored repository record. Git object data lives in gitstore.
type Repo struct {
	ID                  string
	NamespaceID         string
	Name                string
	FullName            string
	Description         string
	DefaultBranch       string
	Visibility          string
	CloneURL            string
	WebURL              string
	MirrorSource        string
	MirrorSourceID      string
	MirrorStatus        string
	AllowMergeCommit    bool
	AllowSquashMerge    bool
	DeleteBranchOnMerge bool
	Archived            bool
	CreatedAt           string
	UpdatedAt           string
	PushedAt            string
}

// CreateRepo inserts a repo record. id is generated by the caller (idgen).
func (db *DB) CreateRepo(ctx context.Context, r Repo) error {
	_, err := db.sql.ExecContext(ctx, `INSERT INTO repos
		(id, namespace_id, name, full_name, default_branch, visibility, clone_url, web_url,
		 mirror_source, mirror_source_id, mirror_status,
		 allow_merge_commit, allow_squash_merge, delete_branch_on_merge,
		 description, archived, created_at, updated_at, pushed_at)
		VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)`,
		r.ID, r.NamespaceID, r.Name, r.FullName, r.DefaultBranch, r.Visibility,
		nullStr(r.CloneURL), nullStr(r.WebURL), nullStr(r.MirrorSource), nullStr(r.MirrorSourceID), nullStr(r.MirrorStatus),
		b2i(r.AllowMergeCommit), b2i(r.AllowSquashMerge), b2i(r.DeleteBranchOnMerge),
		r.Description, b2i(r.Archived),
		now(), now(), nullStr(r.PushedAt))
	if err != nil {
		if isConflict(err) {
			return fmt.Errorf("%w: repo %q", ErrConflict, r.FullName)
		}
		return err
	}
	return nil
}

// GetRepo returns a repo by owner slug + name.
func (db *DB) GetRepo(ctx context.Context, ownerSlug, name string) (Repo, error) {
	row := db.sql.QueryRowContext(ctx, `SELECT r.id, r.namespace_id, r.name, r.full_name, r.default_branch,
		r.visibility, r.clone_url, r.web_url, r.mirror_source, r.mirror_source_id, r.mirror_status,
		r.allow_merge_commit, r.allow_squash_merge, r.delete_branch_on_merge,
		r.created_at, r.updated_at, r.pushed_at,
		COALESCE(r.description, ''), COALESCE(r.archived, 0)
		FROM repos r JOIN namespaces n ON n.id = r.namespace_id
		WHERE n.slug = ? AND r.name = ?`, ownerSlug, name)
	return scanRepo(row)
}

// GetRepoByID returns a repo by its id (used by /repos/_/{id}).
func (db *DB) GetRepoByID(ctx context.Context, id string) (Repo, error) {
	row := db.sql.QueryRowContext(ctx, `SELECT id, namespace_id, name, full_name, default_branch,
		visibility, clone_url, web_url, mirror_source, mirror_source_id, mirror_status,
		allow_merge_commit, allow_squash_merge, delete_branch_on_merge,
		created_at, updated_at, pushed_at,
		COALESCE(description, ''), COALESCE(archived, 0) FROM repos WHERE id = ?`, id)
	return scanRepo(row)
}

// ListRepos returns repos in a namespace, paginated. Pass pageSize<=0 for the
// default (30) and pageToken="" for the first page; the returned nextToken is
// "" when there are no more pages.
func (db *DB) ListRepos(ctx context.Context, ownerSlug string, pageSize int, pageToken string) (repos []Repo, nextToken string, err error) {
	if pageSize <= 0 {
		pageSize = 30
	}
	if pageSize > 100 {
		pageSize = 100
	}
	// Keyset pagination on repo id (monotonic ULID). pageToken is the last id.
	rows, err := db.sql.QueryContext(ctx, `SELECT r.id, r.namespace_id, r.name, r.full_name, r.default_branch,
		r.visibility, r.clone_url, r.web_url, r.mirror_source, r.mirror_source_id, r.mirror_status,
		r.allow_merge_commit, r.allow_squash_merge, r.delete_branch_on_merge,
		r.created_at, r.updated_at, r.pushed_at,
		COALESCE(r.description, ''), COALESCE(r.archived, 0)
		FROM repos r JOIN namespaces n ON n.id = r.namespace_id
		WHERE n.slug = ? AND (? = '' OR r.id > ?)
		ORDER BY r.id ASC LIMIT ?`, ownerSlug, pageToken, pageToken, pageSize+1)
	if err != nil {
		return nil, "", err
	}
	defer rows.Close()
	for rows.Next() {
		r, err := scanRepoRows(rows)
		if err != nil {
			return nil, "", err
		}
		repos = append(repos, r)
	}
	if err := rows.Err(); err != nil {
		return nil, "", err
	}
	if len(repos) > pageSize {
		nextToken = repos[pageSize-1].ID
		repos = repos[:pageSize]
	}
	return repos, nextToken, nil
}

// ListAllRepos returns repos across all namespaces, ordered by updated_at descending.
func (db *DB) ListAllRepos(ctx context.Context, limit int) ([]Repo, error) {
	if limit <= 0 {
		limit = 50
	}
	if limit > 100 {
		limit = 100
	}
	rows, err := db.sql.QueryContext(ctx, `SELECT r.id, r.namespace_id, r.name, r.full_name, r.default_branch,
		r.visibility, r.clone_url, r.web_url, r.mirror_source, r.mirror_source_id, r.mirror_status,
		r.allow_merge_commit, r.allow_squash_merge, r.delete_branch_on_merge,
		r.created_at, r.updated_at, r.pushed_at,
		COALESCE(r.description, ''), COALESCE(r.archived, 0)
		FROM repos r ORDER BY r.updated_at DESC LIMIT ?`, limit)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var repos []Repo
	for rows.Next() {
		r, err := scanRepoRows(rows)
		if err != nil {
			return nil, err
		}
		repos = append(repos, r)
	}
	return repos, rows.Err()
}

// UpdateRepo applies a partial update. Only non-nil fields are changed.
func (db *DB) UpdateRepo(ctx context.Context, ownerSlug, name string, u RepoUpdate) error {
	// Build a dynamic SET clause from the provided fields.
	sets := []string{"updated_at = ?"}
	args := []any{now()}
	add := func(col string, v any) {
		sets = append(sets, col+" = ?")
		args = append(args, v)
	}
	if u.Name != nil {
		add("name", *u.Name)
	}
	if u.FullName != nil {
		add("full_name", *u.FullName)
	}
	if u.Description != nil {
		add("description", *u.Description)
	}
	if u.DefaultBranch != nil {
		add("default_branch", *u.DefaultBranch)
	}
	if u.Visibility != nil {
		add("visibility", *u.Visibility)
	}
	if u.AllowMergeCommit != nil {
		add("allow_merge_commit", b2i(*u.AllowMergeCommit))
	}
	if u.AllowSquashMerge != nil {
		add("allow_squash_merge", b2i(*u.AllowSquashMerge))
	}
	if u.DeleteBranchOnMerge != nil {
		add("delete_branch_on_merge", b2i(*u.DeleteBranchOnMerge))
	}
	if u.Archived != nil {
		add("archived", b2i(*u.Archived))
	}
	args = append(args, ownerSlug, name)
	query := "UPDATE repos SET " + join(sets, ", ") +
		" WHERE namespace_id = (SELECT id FROM namespaces WHERE slug = ?) AND name = ?"
	res, err := db.sql.ExecContext(ctx, query, args...)
	if err != nil {
		return err
	}
	if n, _ := res.RowsAffected(); n == 0 {
		return ErrNotFound
	}
	return nil
}

// RenameRepo renames a repository in a namespace, updating its name and full_name.
func (db *DB) RenameRepo(ctx context.Context, ownerSlug, oldName, newName string) error {
	newName = strings.TrimSpace(newName)
	if newName == "" {
		return fmt.Errorf("repository name cannot be empty")
	}
	newFullName := ownerSlug + "/" + newName
	res, err := db.sql.ExecContext(ctx, `UPDATE repos SET name = ?, full_name = ?, updated_at = ?
		WHERE namespace_id = (SELECT id FROM namespaces WHERE slug = ?) AND name = ?`,
		newName, newFullName, now(), ownerSlug, oldName)
	if err != nil {
		if isConflict(err) {
			return fmt.Errorf("%w: repository %s already exists", ErrConflict, newFullName)
		}
		return err
	}
	if n, _ := res.RowsAffected(); n == 0 {
		return ErrNotFound
	}
	return nil
}

// TransferRepo transfers repository ownership to a different namespace.
func (db *DB) TransferRepo(ctx context.Context, oldOwnerSlug, newOwnerSlug, repoName string) error {
	oldOwnerSlug = strings.TrimSpace(oldOwnerSlug)
	newOwnerSlug = strings.TrimSpace(newOwnerSlug)
	repoName = strings.TrimSpace(repoName)
	if newOwnerSlug == "" || repoName == "" {
		return fmt.Errorf("owner and repo name cannot be empty")
	}
	if strings.EqualFold(oldOwnerSlug, newOwnerSlug) {
		return fmt.Errorf("target owner is the same as current owner")
	}

	targetNs, err := db.GetNamespaceBySlug(ctx, newOwnerSlug)
	if err != nil {
		return fmt.Errorf("target owner namespace %q not found: %w", newOwnerSlug, err)
	}

	newFullName := newOwnerSlug + "/" + repoName
	res, err := db.sql.ExecContext(ctx, `UPDATE repos SET namespace_id = ?, full_name = ?, updated_at = ?
		WHERE namespace_id = (SELECT id FROM namespaces WHERE slug = ?) AND name = ?`,
		targetNs.ID, newFullName, now(), oldOwnerSlug, repoName)
	if err != nil {
		if isConflict(err) {
			return fmt.Errorf("%w: repository %s already exists in target namespace", ErrConflict, newFullName)
		}
		return err
	}
	if n, _ := res.RowsAffected(); n == 0 {
		return ErrNotFound
	}
	return nil
}

// RepoUpdate is a partial repo update; nil fields are left unchanged.
type RepoUpdate struct {
	Name                *string
	FullName            *string
	Description         *string
	DefaultBranch       *string
	Visibility          *string
	AllowMergeCommit    *bool
	AllowSquashMerge    *bool
	DeleteBranchOnMerge *bool
	Archived            *bool
}

// DeleteRepo deletes a repository by owner slug + name.
func (db *DB) DeleteRepo(ctx context.Context, ownerSlug, name string) error {
	res, err := db.sql.ExecContext(ctx, `DELETE FROM repos
		WHERE id IN (
			SELECT r.id FROM repos r JOIN namespaces n ON n.id = r.namespace_id
			WHERE n.slug = ? AND r.name = ?
		)`, ownerSlug, name)
	if err != nil {
		return fmt.Errorf("delete repo: %w", err)
	}
	rows, err := res.RowsAffected()
	if err != nil {
		return err
	}
	if rows == 0 {
		return ErrNotFound
	}
	return nil
}

func scanRepo(row *sql.Row) (Repo, error) {
	return scanRepoCols(row.Scan)
}

func scanRepoRows(rows *sql.Rows) (Repo, error) {
	return scanRepoCols(rows.Scan)
}

func scanRepoCols(scan func(dest ...any) error) (Repo, error) {
	var r Repo
	var cloneURL, webURL, mSrc, mSrcID, mStatus, pushedAt, desc sql.NullString
	var amc, asm, dbom, arch int
	err := scan(&r.ID, &r.NamespaceID, &r.Name, &r.FullName, &r.DefaultBranch,
		&r.Visibility, &cloneURL, &webURL, &mSrc, &mSrcID, &mStatus,
		&amc, &asm, &dbom, &r.CreatedAt, &r.UpdatedAt, &pushedAt,
		&desc, &arch)
	if errors.Is(err, sql.ErrNoRows) {
		return Repo{}, ErrNotFound
	}
	if err != nil {
		return Repo{}, err
	}
	r.CloneURL = cloneURL.String
	r.WebURL = webURL.String
	r.MirrorSource = mSrc.String
	r.MirrorSourceID = mSrcID.String
	r.MirrorStatus = mStatus.String
	r.PushedAt = pushedAt.String
	r.Description = desc.String
	r.AllowMergeCommit = amc != 0
	r.AllowSquashMerge = asm != 0
	r.DeleteBranchOnMerge = dbom != 0
	r.Archived = arch != 0
	return r, nil
}

// ---------- helpers ----------

func nullStr(s string) any {
	if s == "" {
		return nil
	}
	return s
}

func b2i(b bool) int {
	if b {
		return 1
	}
	return 0
}

func join(parts []string, sep string) string { return strings.Join(parts, sep) }

// isConflict reports whether a driver error is a uniqueness violation.
func isConflict(err error) bool {
	return err != nil && (strings.Contains(err.Error(), "UNIQUE constraint failed") ||
		strings.Contains(err.Error(), "constraint failed"))
}
