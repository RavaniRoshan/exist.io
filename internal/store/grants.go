// Grant is one access grant on a namespace or repository. Exactly one of
// UserID, GroupID, or TeamGroup identifies the principal (see the table CHECK).
type Grant struct {
	ID            string
	Scope         string // "namespace" | "repository"
	NamespaceID   string
	RepoID        string // empty for namespace grants
	PrincipalKind string // "user" | "group" | "teamGroup"
	UserID        string
	GroupID       string
	TeamGroup     string // "members" | "admins"
	Permission    string
	CreatedAt     string
	UpdatedAt     string
}

// UpsertGrant inserts or replaces the grant for (scope, target, principal).
// The id is generated by the caller. It returns the stored grant.
func (db *DB) UpsertGrant(ctx context.Context, g Grant) (Grant, error) {
	now := time.Now().UTC().Format(time.RFC3339Nano)
	// Delete any existing grant for the same target+principal, then insert.
	// (Simplest correct upsert given the partial unique indexes.)
	var del string
	var delArgs []any
	if g.Scope == "repository" {
		del = `DELETE FROM grants WHERE scope='repository' AND repo_id=? AND principal_kind=? AND IFNULL(user_id,'')=? AND IFNULL(group_id,'')=? AND IFNULL(team_group,'')=?`
		delArgs = []any{g.RepoID, g.PrincipalKind, g.UserID, g.GroupID, g.TeamGroup}
	} else {
		del = `DELETE FROM grants WHERE scope='namespace' AND namespace_id=? AND principal_kind=? AND IFNULL(user_id,'')=? AND IFNULL(group_id,'')=? AND IFNULL(team_group,'')=?`
		delArgs = []any{g.NamespaceID, g.PrincipalKind, g.UserID, g.GroupID, g.TeamGroup}
	}
	if _, err := db.sql.ExecContext(ctx, del, delArgs...); err != nil {
		return Grant{}, err
	}

	_, err := db.sql.ExecContext(ctx, `INSERT INTO grants
		(id, scope, namespace_id, repo_id, principal_kind, user_id, group_id, team_group, permission, created_at, updated_at)
		VALUES (?,?,?,?,?,?,?,?,?,?,?)`,
		g.ID, g.Scope, g.NamespaceID, nullStr(g.RepoID), g.PrincipalKind,
		nullStr(g.UserID), nullStr(g.GroupID), nullStr(g.TeamGroup), g.Permission, now, now)
	if err != nil {
		if isConflict(err) {
			return Grant{}, fmt.Errorf("%w: grant", ErrConflict)
		}
		return Grant{}, err
	}
	g.CreatedAt, g.UpdatedAt = now, now
	return g, nil
}

// DeleteGrant removes the grant for (scope, target, principal). Returns
// ErrNotFound if no such grant exists.
func (db *DB) DeleteGrant(ctx context.Context, scope, namespaceID, repoID string, principal GrantPrincipal) error {
	var query string
	var args []any
	if scope == "repository" {
		query = `DELETE FROM grants WHERE scope='repository' AND repo_id=? AND principal_kind=? AND IFNULL(user_id,'')=? AND IFNULL(group_id,'')=? AND IFNULL(team_group,'')=?`
		args = []any{repoID, principal.Kind, principal.UserID, principal.GroupID, principal.TeamGroup}
	} else {
		query = `DELETE FROM grants WHERE scope='namespace' AND namespace_id=? AND principal_kind=? AND IFNULL(user_id,'')=? AND IFNULL(group_id,'')=? AND IFNULL(team_group,'')=?`
		args = []any{namespaceID, principal.Kind, principal.UserID, principal.GroupID, principal.TeamGroup}
	}
	res, err := db.sql.ExecContext(ctx, query, args...)
	if err != nil {
		return err
	}
	if n, _ := res.RowsAffected(); n == 0 {
		return ErrNotFound
	}
	return nil
}

// ListNamespaceGrants returns all grants on a namespace, ordered to match
// Origin: admins first, then by principal kind (group, teamGroup admins,
// teamGroup members, user) and id.
func (db *DB) ListNamespaceGrants(ctx context.Context, namespaceID string) ([]Grant, error) {
	rows, err := db.sql.QueryContext(ctx, grantSelect+` WHERE scope='namespace' AND namespace_id=? `+grantOrder, namespaceID)
	if err != nil {
		return nil, err
	}
	return scanGrants(rows)
}

// ListRepositoryGrants returns all grants on a repository, ordered like
// ListNamespaceGrants.
func (db *DB) ListRepositoryGrants(ctx context.Context, repoID string) ([]Grant, error) {
	rows, err := db.sql.QueryContext(ctx, grantSelect+` WHERE scope='repository' AND repo_id=? `+grantOrder, repoID)
	if err != nil {
		return nil, err
	}
	return scanGrants(rows)
}

const grantSelect = `SELECT id, scope, namespace_id, repo_id, principal_kind, user_id, group_id, team_group, permission, created_at, updated_at FROM grants`

// grantOrder matches Origin's documented ordering: admins first, then by
// principal kind (group, team admins, team members, user), then id.
const grantOrder = ` ORDER BY
	CASE WHEN permission IN ('PERMISSION_ADMIN','admin') THEN 0 ELSE 1 END,
	CASE principal_kind WHEN 'group' THEN 0 WHEN 'teamGroup' THEN 1 ELSE 2 END,
	CASE WHEN principal_kind='teamGroup' AND team_group='admins' THEN 0 ELSE 1 END,
	id ASC`

func scanGrants(rows *sql.Rows) ([]Grant, error) {
	defer rows.Close()
	var out []Grant
	for rows.Next() {
		var g Grant
		var repoID, userID, groupID, teamGroup sql.NullString
		if err := rows.Scan(&g.ID, &g.Scope, &g.NamespaceID, &repoID, &g.PrincipalKind,
			&userID, &groupID, &teamGroup, &g.Permission, &g.CreatedAt, &g.UpdatedAt); err != nil {
			return nil, err
		}
		g.RepoID, g.UserID, g.GroupID, g.TeamGroup = repoID.String, userID.String, groupID.String, teamGroup.String
		out = append(out, g)
	}
	return out, rows.Err()
}

// GrantPrincipal identifies the principal of a grant request. Exactly one of
// UserID, GroupID, TeamGroup is set; Kind is "user"|"group"|"teamGroup".
type GrantPrincipal struct {
	Kind      string
	UserID    string
	GroupID   string
	TeamGroup string
}

