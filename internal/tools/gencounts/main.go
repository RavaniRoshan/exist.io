// Command gencounts derives every published capability count from source.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strings"

	"exist.io/internal/mcp"
)

var routePattern = regexp.MustCompile(`mux\.Handle(?:Func)?\("(?:GET|POST|PUT|PATCH|DELETE|HEAD|OPTIONS) ([^"]+)"`)

func main() {
	check := flag.Bool("check", false, "fail when docs/generated/capability_counts.md is stale")
	flag.Parse()

	root, err := findRoot()
	if err != nil {
		fatal(err)
	}
	body, err := render(root)
	if err != nil {
		fatal(err)
	}

	target := filepath.Join(root, "docs", "generated", "capability_counts.md")
	if *check {
		existing, err := os.ReadFile(target)
		if err != nil {
			fatal(fmt.Errorf("read %s: %w", target, err))
		}
		if !bytes.Equal(existing, body) {
			fatal(fmt.Errorf("capability counts drifted; run: go run ./internal/tools/gencounts"))
		}
		fmt.Println("capability counts: up to date")
		return
	}

	if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
		fatal(err)
	}
	if err := os.WriteFile(target, body, 0o644); err != nil {
		fatal(err)
	}
	fmt.Printf("wrote %s\n", target)
}

func findRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("go.mod not found")
		}
		dir = parent
	}
}

func render(root string) ([]byte, error) {
	routes, err := countRoutes(root)
	if err != nil {
		return nil, err
	}
	packages, err := countPackages(root)
	if err != nil {
		return nil, err
	}
	tests, err := countFrontendTests(root)
	if err != nil {
		return nil, err
	}

	var body bytes.Buffer
	body.WriteString("<!-- GENERATED by internal/tools/gencounts; do not edit. Run: go run ./internal/tools/gencounts -->\n\n")
	body.WriteString("# Capability counts\n\n")
	body.WriteString("Derived from source at the current commit. CI fails when this file drifts.\n\n")
	body.WriteString("| Capability | Count | Derived from |\n")
	body.WriteString("| :--- | ---: | :--- |\n")
	fmt.Fprintf(&body, "| MCP tools | %d | `internal/mcp.BuiltinTools()` |\n", len(mcp.BuiltinTools()))
	fmt.Fprintf(&body, "| HTTP route patterns | %d | `mux.Handle*` registrations in `internal/app` and `internal/origin` |\n", routes)
	fmt.Fprintf(&body, "| Go packages | %d | `go list ./...` |\n", packages)
	fmt.Fprintf(&body, "| Frontend test files | %d | `web/src/**/*.test.{ts,tsx}` |\n", tests)
	return body.Bytes(), nil
}

func countRoutes(root string) (int, error) {
	seen := map[string]struct{}{}
	for _, dir := range []string{"internal/app", "internal/origin"} {
		err := filepath.WalkDir(filepath.Join(root, dir), func(path string, entry os.DirEntry, err error) error {
			if err != nil {
				return err
			}
			if entry.IsDir() || !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") {
				return nil
			}
			body, err := os.ReadFile(path)
			if err != nil {
				return err
			}
			for _, match := range routePattern.FindAllSubmatch(body, -1) {
				seen[string(match[1])] = struct{}{}
			}
			return nil
		})
		if err != nil {
			return 0, err
		}
	}
	return len(seen), nil
}

func countPackages(root string) (int, error) {
	command := exec.Command("go", "list", "./...")
	command.Dir = root
	output, err := command.Output()
	if err != nil {
		return 0, fmt.Errorf("go list ./...: %w", err)
	}
	count := 0
	for _, line := range strings.Split(strings.TrimSpace(string(output)), "\n") {
		if line != "" {
			count++
		}
	}
	return count, nil
}

func countFrontendTests(root string) (int, error) {
	count := 0
	err := filepath.WalkDir(filepath.Join(root, "web", "src"), func(path string, entry os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() {
			return nil
		}
		if strings.HasSuffix(path, ".test.ts") || strings.HasSuffix(path, ".test.tsx") {
			count++
		}
		return nil
	})
	return count, err
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}
